export interface InventoryItem {
  id: string;
  area: Area;
  name: string;
  priority: Priority;
  status: InventoryStatus;
  refs: string[];
  note?: string;
  /** pasul concret următor (obligatoriu pentru PARTIAL, MISSING, PLANNED) */
  next?: string;
}

type Spec = [id: string, name: string, priority: Priority, status: InventoryStatus, refs: string[], note?: string, next?: string];

const area = (a: Area, rows: Spec[]): InventoryItem[] =>
  rows.map(([id, name, priority, status, refs, note, next]) => ({
    id: `${a}.${id}`,
    area: a,
    name,
    priority,
    status,
    refs,
    ...(note ? { note } : {}),
    ...(next ? { next } : {}),
  }));

